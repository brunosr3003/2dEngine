#!/usr/bin/env python3
"""Every app icon of Tempest, from ONE master: the Google Play store icon.

Owner, 08/11/2026: "the store icon is good, but once installed the game
icon is an ugly one — always use the store one". The installed icons were a
separate procedural lighthouse (the old tools/ios/gerar_icone.py); now they
all come from `assets/icone/tempest-loja-512.png` (the icon live on Google
Play). Deterministic: running again gives the same files.

    python3 tools/icone_app/gerar.py

Outputs
- assets/ios/AppIcon-1024.png        iOS (actool) and Mac (.icns, build-mac.sh)
- Android res/mipmap-*/              adaptive (API 26+) + legacy/round (24-25)
- crates/client/windows/tempest.ico  embedded in Tempest.exe (build.rs)
- crates/client/src/icone_janela/    16/32/64 RGBA for the window/taskbar icon
"""
import os

from PIL import Image, ImageDraw, ImageFilter

RAIZ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MESTRE = os.path.join(RAIZ, "assets", "icone", "tempest-loja-512.png")
RES = os.path.join(RAIZ, "crates", "client", "android", "app", "src", "main", "res")
DENS = {"mdpi": 1.0, "hdpi": 1.5, "xhdpi": 2.0, "xxhdpi": 3.0, "xxxhdpi": 4.0}


def lado(img, n):
    return img.resize((n, n), Image.LANCZOS)


def mascara_redonda(n, raio):
    m = Image.new("L", (n * 4, n * 4), 0)
    ImageDraw.Draw(m).rounded_rectangle((0, 0, n * 4 - 1, n * 4 - 1), raio * 4, fill=255)
    return m.resize((n, n), Image.LANCZOS)


def mascara_circulo(n):
    m = Image.new("L", (n * 4, n * 4), 0)
    ImageDraw.Draw(m).ellipse((0, 0, n * 4 - 1, n * 4 - 1), fill=255)
    return m.resize((n, n), Image.LANCZOS)


def salva(img, *partes):
    caminho = os.path.join(RAIZ, *partes)
    os.makedirs(os.path.dirname(caminho), exist_ok=True)
    img.save(caminho, optimize=True)


def main():
    m = Image.open(MESTRE).convert("RGBA")
    opaco = Image.new("RGBA", m.size, (0, 0, 0, 255))
    opaco.alpha_composite(m)
    rgb = opaco.convert("RGB")

    # iOS + Mac: 1024 opaque (the App Store refuses alpha); the OS masks it.
    salva(lado(rgb, 1024), "assets", "ios", "AppIcon-1024.png")

    # Android adaptive: 108dp layers, 72dp visible. The whole store square
    # goes in the visible 72dp (launcher masks only cut the corners, like the
    # Play Store's own rounded mask); the background is the same picture,
    # blurred, filling the bleed the launcher shows while animating.
    for nome, k in DENS.items():
        cheio = round(108 * k)
        visivel = round(72 * k)
        margem = (cheio - visivel) // 2
        fundo = lado(rgb, cheio).filter(ImageFilter.GaussianBlur(6 * k))
        frente = Image.new("RGBA", (cheio, cheio), (0, 0, 0, 0))
        frente.paste(lado(opaco, visivel), (margem, margem))
        d = f"mipmap-{nome}"
        salva(fundo, RES, d, "ic_launcher_background.png")
        salva(frente, RES, d, "ic_launcher_foreground.png")
        # Legacy (API 24-25): 48dp, rounded square and circle.
        n = round(48 * k)
        quadrado = lado(opaco, n)
        q = Image.new("RGBA", (n, n), (0, 0, 0, 0))
        q.paste(quadrado, (0, 0), mascara_redonda(n, n * 0.18))
        salva(q, RES, d, "ic_launcher.png")
        c = Image.new("RGBA", (n, n), (0, 0, 0, 0))
        c.paste(quadrado, (0, 0), mascara_circulo(n))
        salva(c, RES, d, "ic_launcher_round.png")
    xml = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/icone_app/gerar.py from the Google Play icon. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
"""
    for arq in ("ic_launcher.xml", "ic_launcher_round.xml"):
        caminho = os.path.join(RES, "mipmap-anydpi-v26", arq)
        os.makedirs(os.path.dirname(caminho), exist_ok=True)
        with open(caminho, "w") as f:
            f.write(xml)

    # Windows .ico (Explorer, taskbar pin, Start menu).
    ico = os.path.join(RAIZ, "crates", "client", "windows", "tempest.ico")
    os.makedirs(os.path.dirname(ico), exist_ok=True)
    lado(opaco, 256).save(ico, sizes=[(s, s) for s in (16, 24, 32, 48, 64, 128, 256)])

    # Window icon while the game runs (miniquad conf.icon: Windows/Mac/X11).
    for n in (16, 32, 64):
        caminho = os.path.join(RAIZ, "crates", "client", "src", "icone_janela", f"{n}.rgba")
        os.makedirs(os.path.dirname(caminho), exist_ok=True)
        with open(caminho, "wb") as f:
            f.write(lado(opaco, n).tobytes())
    print("ok")


if __name__ == "__main__":
    main()
