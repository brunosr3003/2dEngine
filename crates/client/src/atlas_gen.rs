//! Gerador de atlas de desenvolvimento em tempo de execucao.
//!
//! Produz um PNG 256x256 RGBA com:
//!   Linha 0  (y 0..15)   : tiles de terreno (16x16 px cada)
//!   Linha 1  (y 16..31)  : sprites de jogador — 8 frames (walk 4 dirs)
//!   Linha 2  (y 32..47)  : sprites de inimigo basico — 4 frames
//!   Linhas 4-6 (y 64..87): fonte bitmap 8x8 (ASCII 32-127, 32 colunas)
//!
//! Substitua por um PNG real quando tiver arte. O layout de UVs e
//! descrito em `AtlasLayout` — use os campos para criar `TileDef`,
//! `BitmapFont` e clips de animacao.

use glam::Vec2;

pub const ATLAS_W: u32 = 256;
pub const ATLAS_H: u32 = 256;
pub const TILE_PX: u32 = 16; // pixels por tile no atlas
pub const FONT_CHAR_PX: u32 = 8;
pub const FONT_COLS: u32 = 32;
pub const FONT_ORIGIN_Y: u32 = 64; // inicio da area de fonte em px

/// IDs logicos de tile — usados no WorldMap e no TileDef lookup.
pub mod tile_id {
    pub const FLOOR: u16 = 1;
    pub const WALL:  u16 = 2;
    pub const DIRT:  u16 = 3;
    pub const WATER: u16 = 4;
    #[allow(dead_code)]
    pub const WOOD:  u16 = 5;
}

/// Descricao do layout para usar fora do modulo.
pub struct AtlasLayout {
    #[allow(dead_code)]
    pub white_uv:        (Vec2, Vec2),
    pub tile_uvs:        Vec<(Vec2, Vec2)>, // index = tile_id (0=empty stub)
    /// Frames do jogador: (uv_min, uv_max) por frame.
    /// [0-3] = walk-down, [4-7] = walk-right
    pub player_uvs:      Vec<(Vec2, Vec2)>,
    /// Frames do inimigo basico: [0-3]
    pub enemy_uvs:       Vec<(Vec2, Vec2)>,
    pub font_origin_x:   u32,
    pub font_origin_y:   u32,
    pub font_char_px_w:  u32,
    pub font_char_px_h:  u32,
    pub font_cols:       u32,
}

/// Gera atlas e retorna (pixels RGBA, layout).
pub fn generate() -> (Vec<u8>, AtlasLayout) {
    let mut px = vec![0u8; (ATLAS_W * ATLAS_H * 4) as usize];

    // ---- Pixel branco puro (canto (0,0) = 1x1) para DebugDraw ----
    set(&mut px, 0, 0, [255, 255, 255, 255]);

    // ---- Tiles de terreno (linha 0, colunas 1-7) ----
    paint_tile(&mut px, 1, 0, grass_pixel);
    paint_tile(&mut px, 2, 0, wall_pixel);
    paint_tile(&mut px, 3, 0, dirt_pixel);
    paint_tile(&mut px, 4, 0, water_pixel);
    paint_tile(&mut px, 5, 0, wood_pixel);

    // ---- Sprites de jogador (linha 1, colunas 0-7) ----
    for frame in 0u32..4 {
        paint_char_sprite(&mut px, frame, 1, [70, 130, 70, 255], frame);   // walk-down
        paint_char_sprite(&mut px, frame + 4, 1, [70, 130, 70, 255], frame); // walk-right (mesmo sprite, flip via UV no anim)
    }

    // ---- Sprites de inimigo basico (linha 2, colunas 0-3) ----
    for frame in 0u32..4 {
        paint_char_sprite(&mut px, frame, 2, [180, 50, 50, 255], frame);
    }

    // ---- Fonte 8x8 (linhas 4-6, a partir de y=64) ----
    paint_font(&mut px);

    let layout = build_layout();
    (px, layout)
}

// ---------------------------------------------------------------------------
// Pintores de tile
// ---------------------------------------------------------------------------

fn grass_pixel(lx: u32, ly: u32) -> [u8; 4] {
    let dot = (lx * 3 + ly * 7) % 5 == 0;
    let v: u8 = if dot { 60 } else { 90 };
    [40, v, 35, 255]
}

fn wall_pixel(lx: u32, ly: u32) -> [u8; 4] {
    let mortar_h = ly % 6 == 0;
    let mortar_v = (lx + (ly / 6) * 8) % 9 == 0;
    let v: u8 = if mortar_h || mortar_v { 70 } else { 130 };
    [v, v, v, 255]
}

fn dirt_pixel(lx: u32, ly: u32) -> [u8; 4] {
    let noise = ((lx * 13 + ly * 7) % 4) as u8;
    [100 + noise * 5, 70 + noise * 3, 45 + noise * 2, 255]
}

fn water_pixel(lx: u32, ly: u32) -> [u8; 4] {
    let wave = ((lx + ly * 2) % 6) as u8;
    [30 + wave, 80 + wave * 2, 160 + wave, 255]
}

fn wood_pixel(lx: u32, ly: u32) -> [u8; 4] {
    let plank = ly / 4;
    let grain = ((lx * 2 + plank * 3) % 5) as u8;
    [110 + grain * 5, 70 + grain * 3, 35 + grain, 255]
}

fn paint_tile(px: &mut [u8], col: u32, row: u32, f: fn(u32, u32) -> [u8; 4]) {
    let ox = col * TILE_PX;
    let oy = row * TILE_PX;
    for ly in 0..TILE_PX {
        for lx in 0..TILE_PX {
            set(px, ox + lx, oy + ly, f(lx, ly));
        }
    }
}

// ---------------------------------------------------------------------------
// Pintor de sprite de personagem (top-down view, 16x16)
// ---------------------------------------------------------------------------

fn paint_char_sprite(px: &mut [u8], col: u32, row: u32, body: [u8; 4], frame: u32) {
    let ox = col * TILE_PX;
    let oy = row * TILE_PX;

    // Transparente por padrao
    for ly in 0..TILE_PX {
        for lx in 0..TILE_PX {
            set(px, ox + lx, oy + ly, [0, 0, 0, 0]);
        }
    }

    // Cabeca (skin, linhas 1-6, cols 4-11)
    let skin = [220, 175, 120, 255];
    for ly in 1..7u32 {
        for lx in 4..12u32 {
            set(px, ox + lx, oy + ly, skin);
        }
    }
    // Olhos
    set(px, ox + 6, oy + 3, [40, 30, 20, 255]);
    set(px, ox + 9, oy + 3, [40, 30, 20, 255]);

    // Corpo (body color, linhas 7-11)
    for ly in 7..12u32 {
        for lx in 3..13u32 {
            set(px, ox + lx, oy + ly, body);
        }
    }

    // Pernas (animadas por frame)
    let (dl, dr): (i32, i32) = match frame % 4 {
        0 => (0, 0),
        1 => (-1, 1),
        2 => (0, 0),
        _ => (1, -1),
    };
    let leg = [body[0] / 2, body[1] / 2, body[2] / 2, 255];
    for ly in 12..16u32 {
        let lx = (4i32 + dl) as u32;
        let rx = (11i32 + dr) as u32;
        if lx < TILE_PX { set(px, ox + lx, oy + ly, leg); }
        if rx < TILE_PX { set(px, ox + rx, oy + ly, leg); }
    }

    // Sombra (linha 15, meia-transparente)
    set(px, ox + 7,  oy + 15, [0, 0, 0, 80]);
    set(px, ox + 8,  oy + 15, [0, 0, 0, 80]);
}

