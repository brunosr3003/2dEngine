fn paint_font(px: &mut [u8]) {
    for (idx, glyph) in FONT.iter().enumerate() {
        let col = (idx as u32) % FONT_COLS;
        let row = (idx as u32) / FONT_COLS;
        let ox = col * FONT_CHAR_PX;
        let oy = FONT_ORIGIN_Y + row * FONT_CHAR_PX;
        for (gy, &byte) in glyph.iter().enumerate() {
            for bit in 0..8u32 {
                let on = (byte >> (7 - bit)) & 1 == 1;
                let color = if on { [255, 255, 255, 255] } else { [0, 0, 0, 0] };
                set(px, ox + bit, oy + gy as u32, color);
            }
        }
    }
}

// ---------------------------------------------------------------------------
// Layout de UVs
// ---------------------------------------------------------------------------

fn uv(px_x: u32, px_y: u32, pw: u32, ph: u32) -> (Vec2, Vec2) {
    let iw = ATLAS_W as f32;
    let ih = ATLAS_H as f32;
    (
        Vec2::new(px_x as f32 / iw, px_y as f32 / ih),
        Vec2::new((px_x + pw) as f32 / iw, (px_y + ph) as f32 / ih),
    )
}

fn tile_uv(col: u32, row: u32) -> (Vec2, Vec2) {
    uv(col * TILE_PX, row * TILE_PX, TILE_PX, TILE_PX)
}

fn build_layout() -> AtlasLayout {
    let white_uv = uv(0, 0, 1, 1);

    // tile_uvs[0] = stub vazio (nao renderizado), [1-5] = floor..wood
    let tile_uvs = vec![
        uv(0, 0, 0, 0),           // 0: vazio (nao renderiza)
        tile_uv(1, 0),             // 1: FLOOR (grass)
        tile_uv(2, 0),             // 2: WALL
        tile_uv(3, 0),             // 3: DIRT
        tile_uv(4, 0),             // 4: WATER
        tile_uv(5, 0),             // 5: WOOD
    ];

    let player_uvs: Vec<_> = (0..8).map(|f| tile_uv(f, 1)).collect();
    let enemy_uvs:  Vec<_> = (0..4).map(|f| tile_uv(f, 2)).collect();

    AtlasLayout {
        white_uv,
        tile_uvs,
        player_uvs,
        enemy_uvs,
        font_origin_x:  0,
        font_origin_y:  FONT_ORIGIN_Y,
        font_char_px_w: FONT_CHAR_PX,
        font_char_px_h: FONT_CHAR_PX,
        font_cols:      FONT_COLS,
    }
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

fn set(px: &mut [u8], x: u32, y: u32, color: [u8; 4]) {
    if x >= ATLAS_W || y >= ATLAS_H { return; }
    let i = ((y * ATLAS_W + x) * 4) as usize;
    px[i..i + 4].copy_from_slice(&color);
}
